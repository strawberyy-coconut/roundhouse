//! The descriptors `routes!` emits: a module tree of route declarations.
//!
//! A `routes!` invocation produces a `pub const MODULE: Module` (plus
//! `__roundhouse_fragment()`), and an application composes modules explicitly with `...module`
//! spreads, `App::include` or `app!(state, module)`. Resolution walks that tree.
//!
//! The constructors are public (but hidden from docs) because macro expansions in user crates
//! call them.

use std::any::Any;
use std::fmt;

use crate::auth::AuthGuard;
use crate::doc::{DocContext, OperationDoc};
use axum::Router;
use axum::routing::MethodRouter;

/// HTTP methods a table entry may declare.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Method {
    Get,
    Post,
    Put,
    Patch,
    Delete,
    Head,
    Options,
    Trace,
    Any,
}

impl Method {
    pub fn as_str(self) -> &'static str {
        match self {
            Method::Get => "GET",
            Method::Post => "POST",
            Method::Put => "PUT",
            Method::Patch => "PATCH",
            Method::Delete => "DELETE",
            Method::Head => "HEAD",
            Method::Options => "OPTIONS",
            Method::Trace => "TRACE",
            Method::Any => "ANY",
        }
    }

    pub fn to_http(self) -> Option<http::Method> {
        Some(match self {
            Method::Get => http::Method::GET,
            Method::Post => http::Method::POST,
            Method::Put => http::Method::PUT,
            Method::Patch => http::Method::PATCH,
            Method::Delete => http::Method::DELETE,
            Method::Head => http::Method::HEAD,
            Method::Options => http::Method::OPTIONS,
            Method::Trace => http::Method::TRACE,
            Method::Any => return None,
        })
    }

    pub fn to_utoipa(self) -> Option<utoipa::openapi::path::HttpMethod> {
        use utoipa::openapi::path::HttpMethod;
        Some(match self {
            Method::Get => HttpMethod::Get,
            Method::Post => HttpMethod::Post,
            Method::Put => HttpMethod::Put,
            Method::Patch => HttpMethod::Patch,
            Method::Delete => HttpMethod::Delete,
            Method::Head => HttpMethod::Head,
            Method::Options => HttpMethod::Options,
            Method::Trace => HttpMethod::Trace,
            Method::Any => return None,
        })
    }
}

impl fmt::Display for Method {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

/// Whether a route's declared constraints are enforced.
///
/// This replaces the old `validate` / `validate_body` pair, which allowed the meaningless
/// combination `validate = false, validate_body = true`. The macro syntax is unchanged; the
/// booleans are lowered to one policy while the route table is expanded.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ValidationPolicy {
    /// Validate path/query/form parts and the request body (default).
    Schema,
    /// Validate parts only; the body is an explicit, quiet opt-out.
    PartsOnly,
    /// Validate nothing for this route. An unverified body is loud under `strict()` unless the
    /// entry acknowledges it.
    Off,
}

impl ValidationPolicy {
    /// Whether path/query/form constraints run.
    pub const fn validates_parts(self) -> bool {
        !matches!(self, Self::Off)
    }

    /// Whether the request body is validated.
    pub const fn validates_body(self) -> bool {
        matches!(self, Self::Schema)
    }

    /// `PartsOnly` is a deliberate body-only decision, so the build does not require an
    /// acknowledgement for the resulting unverified-body marker.
    pub const fn body_opt_out_is_explicit(self) -> bool {
        matches!(self, Self::PartsOnly)
    }
}

/// `fn(Router) -> Router` generated by a module-level `layer = ..`.
///
/// The router is `Router<()>`: module layers are applied after route state has been provided, so
/// the factory needs no knowledge of the app's state type.
pub type ModuleLayer = fn(Router<()>) -> Router<()>;

/// `fn(MethodRouter) -> MethodRouter` generated by a per-entry `layer = ..`.
pub type RouteLayer = fn(MethodRouter<()>) -> MethodRouter<()>;

/// One route declaration from a `routes!` table.
pub struct RouteRecord {
    pub(crate) module_path: &'static str,
    pub(crate) file: &'static str,
    pub(crate) line: u32,
    pub(crate) method: Method,
    pub(crate) path: &'static str,
    /// An optional `path = "..."` assertion checked against the resolved binding.
    pub(crate) assert_path: Option<&'static str>,
    /// An explicit `operation_id = "..."`; `None` derives one from the module and handler.
    pub(crate) operation_id: Option<&'static str>,
    pub(crate) handler_name: &'static str,
    pub(crate) tags: &'static [&'static str],
    /// Guards declared on this table entry; applied unless the handler already requires the
    /// same scheme.
    pub(crate) security: &'static [AuthGuard],
    /// Scheme names the handler itself requires (`Auth<A>`, not `Option<Auth<A>>`).
    pub(crate) required_auth: &'static [&'static str],
    /// Scheme names the generated shim enforces; the guard layer is skipped for these.
    pub(crate) shim_auth: &'static [&'static str],
    pub(crate) hidden: bool,
    pub(crate) absolute: bool,
    /// What the route's constraint validation covers.
    pub(crate) validation: ValidationPolicy,
    /// An explicit acknowledgement of an intentional unverified marker, with the author's
    /// reason. Suppresses the build diagnostic and lets `strict()` pass.
    pub(crate) unverified: Option<&'static str>,
    pub(crate) deprecated: bool,
    pub(crate) anonymous: bool,
    pub(crate) state: fn() -> Option<std::any::TypeId>,
    pub(crate) state_name: fn() -> &'static str,
    pub(crate) handler: fn() -> Box<dyn Any + Send + Sync>,
    pub(crate) layer: Option<RouteLayer>,
    pub(crate) docs: fn(&mut DocContext<'_>) -> OperationDoc,
    /// A `doc = |docs| ..` hook from the table entry. It runs after the handler's inferred
    /// documentation and before the document checks, so hand-written parameters still pass
    /// through the capture and conflict validation.
    pub(crate) doc: Option<fn(&mut OperationDoc)>,
}

/// The named fields `routes!` uses to construct a [`RouteRecord`].
///
/// This exists so generated code can name each field instead of relying on the positional order
/// of a large constructor. It is macro plumbing, not part of the stable API.
#[doc(hidden)]
pub struct RouteSpec {
    pub module_path: &'static str,
    pub file: &'static str,
    pub line: u32,
    pub method: Method,
    pub path: &'static str,
    pub assert_path: Option<&'static str>,
    pub operation_id: Option<&'static str>,
    pub handler_name: &'static str,
    pub tags: &'static [&'static str],
    pub security: &'static [AuthGuard],
    pub required_auth: &'static [&'static str],
    pub shim_auth: &'static [&'static str],
    pub hidden: bool,
    pub absolute: bool,
    pub validation: ValidationPolicy,
    pub unverified: Option<&'static str>,
    pub deprecated: bool,
    pub anonymous: bool,
    pub state: fn() -> Option<std::any::TypeId>,
    pub state_name: fn() -> &'static str,
    pub handler: fn() -> Box<dyn Any + Send + Sync>,
    pub layer: Option<RouteLayer>,
    pub docs: fn(&mut DocContext<'_>) -> OperationDoc,
    pub doc: Option<fn(&mut OperationDoc)>,
}

impl RouteRecord {
    /// Construct a record from named fields. Called by `routes!`; not part of the stable API.
    #[doc(hidden)]
    pub const fn from_spec(spec: RouteSpec) -> Self {
        Self {
            module_path: spec.module_path,
            file: spec.file,
            line: spec.line,
            method: spec.method,
            path: spec.path,
            assert_path: spec.assert_path,
            operation_id: spec.operation_id,
            handler_name: spec.handler_name,
            tags: spec.tags,
            security: spec.security,
            required_auth: spec.required_auth,
            shim_auth: spec.shim_auth,
            hidden: spec.hidden,
            absolute: spec.absolute,
            validation: spec.validation,
            unverified: spec.unverified,
            deprecated: spec.deprecated,
            anonymous: spec.anonymous,
            state: spec.state,
            state_name: spec.state_name,
            handler: spec.handler,
            layer: spec.layer,
            docs: spec.docs,
            doc: spec.doc,
        }
    }

    pub fn location(&self) -> String {
        format!("{}:{}", self.file, self.line)
    }

    /// The constraint-validation policy declared for this route.
    pub fn validation(&self) -> ValidationPolicy {
        self.validation
    }

    pub fn source(&self) -> String {
        format!("{}  {}", self.module_path, self.location())
    }

    pub fn source_ref(&self) -> crate::build_error::Source {
        crate::build_error::Source::new(self.module_path, self.file, self.line)
    }
}

/// One module in the explicit route tree.
///
/// A module carries the prefix, tags, security, layers and documentation shared by the routes it
/// declares and by its children. `routes!` emits one; `...module` spreads reference a child's
/// `MODULE` directly. An application roots the tree with [`App::include`](crate::App::include) or
/// a `routes!` fragment.
pub struct Module {
    pub(crate) module_path: &'static str,
    pub(crate) file: &'static str,
    pub(crate) line: u32,
    pub(crate) prefix: &'static str,
    pub(crate) tags: &'static [&'static str],
    pub(crate) security: &'static [AuthGuard],
    pub(crate) hidden: bool,
    /// Clear inherited security guards for this module and its children.
    pub(crate) anonymous: bool,
    pub(crate) layer: Option<ModuleLayer>,
    pub(crate) doc: Option<fn() -> crate::doc::layer::LayerDoc>,
    pub(crate) routes: &'static [RouteRecord],
    pub(crate) children: &'static [&'static Module],
}

impl fmt::Debug for Module {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Module")
            .field("module_path", &self.module_path)
            .field("prefix", &self.prefix)
            .field("routes", &self.routes.len())
            .field("children", &self.children.len())
            .finish()
    }
}

/// The named fields `routes!` uses to construct a [`Module`].
///
/// Macro plumbing; not part of the stable API.
#[doc(hidden)]
pub struct ModuleSpec {
    pub module_path: &'static str,
    pub file: &'static str,
    pub line: u32,
    pub prefix: &'static str,
    pub tags: &'static [&'static str],
    pub security: &'static [AuthGuard],
    pub hidden: bool,
    pub anonymous: bool,
    pub layer: Option<ModuleLayer>,
    pub doc: Option<fn() -> crate::doc::layer::LayerDoc>,
    pub routes: &'static [RouteRecord],
    pub children: &'static [&'static Module],
}

impl Module {
    /// Construct a module from named fields. Called by `routes!`; not part of the stable API.
    #[doc(hidden)]
    pub const fn from_spec(spec: ModuleSpec) -> Self {
        Self {
            module_path: spec.module_path,
            file: spec.file,
            line: spec.line,
            prefix: spec.prefix,
            tags: spec.tags,
            security: spec.security,
            hidden: spec.hidden,
            anonymous: spec.anonymous,
            layer: spec.layer,
            doc: spec.doc,
            routes: spec.routes,
            children: spec.children,
        }
    }

    pub fn location(&self) -> String {
        format!("{}:{}", self.file, self.line)
    }

    pub fn source_ref(&self) -> crate::build_error::Source {
        crate::build_error::Source::new(self.module_path, self.file, self.line)
    }

    /// The routes declared directly by this module, excluding children.
    pub fn routes(&self) -> &'static [RouteRecord] {
        self.routes
    }

    /// The modules composed under this one.
    pub fn children(&self) -> &'static [&'static Module] {
        self.children
    }
}
