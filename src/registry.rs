//! Link-time registry: the records `routes!` and `mount!` submit.

use std::any::{Any, TypeId};
use std::fmt;

use axum::Router;
use axum::routing::MethodRouter;
use utoipa::openapi::schema::Components;

use crate::doc::HandlerDocs;

/// HTTP methods a table entry may declare.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Method {
    Get,
    Post,
    Put,
    Patch,
    Delete,
    Head,
    Options,
    Trace,
    Any,
}

impl Method {
    pub fn as_str(self) -> &'static str {
        match self {
            Method::Get => "GET",
            Method::Post => "POST",
            Method::Put => "PUT",
            Method::Patch => "PATCH",
            Method::Delete => "DELETE",
            Method::Head => "HEAD",
            Method::Options => "OPTIONS",
            Method::Trace => "TRACE",
            Method::Any => "ANY",
        }
    }

    pub fn to_http(self) -> Option<http::Method> {
        Some(match self {
            Method::Get => http::Method::GET,
            Method::Post => http::Method::POST,
            Method::Put => http::Method::PUT,
            Method::Patch => http::Method::PATCH,
            Method::Delete => http::Method::DELETE,
            Method::Head => http::Method::HEAD,
            Method::Options => http::Method::OPTIONS,
            Method::Trace => http::Method::TRACE,
            Method::Any => return None,
        })
    }

    pub fn to_utoipa(self) -> Option<utoipa::openapi::path::HttpMethod> {
        use utoipa::openapi::path::HttpMethod;
        Some(match self {
            Method::Get => HttpMethod::Get,
            Method::Post => HttpMethod::Post,
            Method::Put => HttpMethod::Put,
            Method::Patch => HttpMethod::Patch,
            Method::Delete => HttpMethod::Delete,
            Method::Head => HttpMethod::Head,
            Method::Options => HttpMethod::Options,
            Method::Trace => HttpMethod::Trace,
            Method::Any => return None,
        })
    }
}

impl fmt::Display for Method {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

/// `fn(Router) -> Router` generated by `mount!(layer = ..)`.
///
/// The router is `Router<()>`: module layers are applied after route state has been provided, so
/// the factory needs no knowledge of the app's state type.
pub type MountLayer = fn(Router<()>) -> Router<()>;

/// `fn(MethodRouter) -> MethodRouter` generated by a per-entry `layer = ..`.
pub type RouteLayer = fn(MethodRouter<()>) -> MethodRouter<()>;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LayerMode {
    Full,
    Route,
}

/// One row from a `routes!` table.
pub struct RouteRecord {
    pub module_path: &'static str,
    pub file: &'static str,
    pub line: u32,
    pub method: Method,
    pub path: &'static str,
    pub operation_id: &'static str,
    pub summary: Option<&'static str>,
    pub description: Option<&'static str>,
    pub tags: &'static [&'static str],
    pub security: &'static [&'static str],
    pub hidden: bool,
    pub absolute: bool,
    pub validate: bool,
    pub deprecated: bool,
    pub public: bool,
    pub responses: fn(&mut Components) -> Vec<crate::doc::ResponseDoc>,
    pub state: fn() -> Option<TypeId>,
    pub state_name: fn() -> &'static str,
    pub handler: fn() -> Box<dyn Any + Send + Sync>,
    pub layer: Option<RouteLayer>,
    pub docs: fn(&mut Components) -> HandlerDocs,
}

impl RouteRecord {
    pub fn location(&self) -> String {
        format!("{}:{}", self.file, self.line)
    }

    pub fn source(&self) -> String {
        format!("{}  {}", self.module_path, self.location())
    }

    pub fn source_ref(&self) -> crate::build_error::Source {
        crate::build_error::Source::new(self.module_path, self.file, self.line)
    }
}

/// One `mount!` from a module.
pub struct MountRecord {
    pub module_path: &'static str,
    pub file: &'static str,
    pub line: u32,
    pub prefix: &'static str,
    pub tags: &'static [&'static str],
    pub security: &'static [&'static str],
    pub hidden: bool,
    pub layer: Option<MountLayer>,
    pub layer_mode: LayerMode,
    pub doc: Option<fn() -> crate::doc::layer::LayerDoc>,
}

impl MountRecord {
    pub fn location(&self) -> String {
        format!("{}:{}", self.file, self.line)
    }
}

/// Documentation registered by `#[derive(ApiResponse)]` / `#[derive(ApiError)]`.
///
/// Handlers join to it by `std::any::type_name`, so a hand-written `IntoResponse` type is simply
/// absent from the document rather than a compile error.
pub struct ResponseRecord {
    pub type_key: fn() -> &'static str,
    pub docs: fn(&mut Components) -> Vec<crate::doc::ResponseDoc>,
}

inventory::collect!(RouteRecord);
inventory::collect!(MountRecord);
inventory::collect!(ResponseRecord);

/// Query parameters documented by `#[derive(QueryParams)]`.
pub struct QueryDocRecord {
    pub type_key: fn() -> &'static str,
    pub params: fn(&mut Components) -> Vec<crate::doc::Param>,
}

inventory::collect!(QueryDocRecord);

/// Type names used to disambiguate components that share a simple name.
pub struct ComponentTypeRecord {
    pub simple: &'static str,
    pub module: &'static str,
}

inventory::collect!(ComponentTypeRecord);
